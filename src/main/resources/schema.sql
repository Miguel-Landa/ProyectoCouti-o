CREATE TABLE IF NOT EXISTS proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    rfc VARCHAR(50) UNIQUE,
    telefono VARCHAR(50),
    email VARCHAR(100),
    direccion VARCHAR(300)
);


CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(100) NOT NULL UNIQUE,
    nombre VARCHAR(300) NOT NULL,
    costo_compra DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    precio DECIMAL(12, 2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    proveedor_id BIGINT REFERENCES proveedores(id) ON DELETE SET NULL
);


CREATE TABLE IF NOT EXISTS compras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura VARCHAR(100) NOT NULL UNIQUE,
    proveedor VARCHAR(200) NOT NULL,
    fecha VARCHAR(50) NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    iva DECIMAL(12, 2) NOT NULL,
    total DECIMAL(12, 2) NOT NULL
);


CREATE TABLE IF NOT EXISTS compra_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id BIGINT NOT NULL REFERENCES compras(id) ON DELETE CASCADE,
    producto_id VARCHAR(50),
    sku VARCHAR(100) NOT NULL,
    nombre VARCHAR(300) NOT NULL,
    costo DECIMAL(12, 2) NOT NULL,
    cantidad INTEGER NOT NULL,
    importe DECIMAL(12, 2) NOT NULL
);


CREATE TABLE IF NOT EXISTS citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(50) NOT NULL UNIQUE,
    cliente VARCHAR(200) NOT NULL,
    telefono VARCHAR(50),
    correo VARCHAR(100),
    mecanico VARCHAR(200),
    moto VARCHAR(200) NOT NULL,
    placas VARCHAR(50) NOT NULL,
    servicio VARCHAR(500) NOT NULL,
    modalidad VARCHAR(100) NOT NULL DEFAULT 'Cita Previa',
    fecha_hora VARCHAR(100) NOT NULL,
    pago_registrado_id VARCHAR(36)
);


