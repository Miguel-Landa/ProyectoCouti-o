CREATE TABLE IF NOT EXISTS cobros (
    id VARCHAR(36) PRIMARY KEY,
    folio VARCHAR(100) NOT NULL UNIQUE,
    cliente VARCHAR(200) NOT NULL,
    motocicleta VARCHAR(200) NOT NULL,
    placas VARCHAR(50) NOT NULL,
    servicio_solicitado VARCHAR(500) NOT NULL,
    servicio_realizado VARCHAR(500) NOT NULL,
    mecanico VARCHAR(200) NOT NULL,
    fecha_pago BIGINT NOT NULL,
    mano_obra DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    servicio_extra_descripcion VARCHAR(500),
    servicio_extra_precio DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    subtotal DECIMAL(12, 2) NOT NULL,
    iva DECIMAL(12, 2) NOT NULL,
    total DECIMAL(12, 2) NOT NULL
);


CREATE TABLE IF NOT EXISTS cobro_refacciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cobro_id VARCHAR(36) NOT NULL REFERENCES cobros(id) ON DELETE CASCADE,
    sku VARCHAR(100) NOT NULL,
    nombre VARCHAR(300) NOT NULL,
    precio_unitario DECIMAL(12, 2) NOT NULL,
    cantidad INTEGER NOT NULL,
    importe DECIMAL(12, 2) NOT NULL
);


CREATE TABLE IF NOT EXISTS ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_numero INTEGER,
    cliente VARCHAR(200) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    pago VARCHAR(100) NOT NULL,
    fecha VARCHAR(50) NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    iva DECIMAL(12, 2) NOT NULL,
    total DECIMAL(12, 2) NOT NULL
);


CREATE TABLE IF NOT EXISTS venta_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(id) ON DELETE CASCADE,
    producto_id VARCHAR(50),
    producto VARCHAR(300) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio DECIMAL(12, 2) NOT NULL,
    importe DECIMAL(12, 2) NOT NULL
); 